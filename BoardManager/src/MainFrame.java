    // 회원 테이블 로드
    private void loadMemberTable() {
        DefaultTableModel model = (DefaultTableModel) MemTable.getModel();
        model.setRowCount(0); // 초기화
        
        String sql = "SELECT id, username, name, student_id, gender, role, birth_date FROM users";

        DBConnection db = new DBConnection();

        // try-with-resources: Connection, PreparedStatement, ResultSet 자동 닫기
        try (Connection conn = db.getConnection();
             PreparedStatement pstmt = conn.prepareStatement(sql);
             ResultSet rs = pstmt.executeQuery()) {

            while (rs.next()) {
                String role = rs.getString("role");
                String roleKorean = convertRoleToKorean(role);

                model.addRow(new Object[]{
                    rs.getInt("id"),
                    rs.getString("username"),
                    rs.getString("name"),
                    rs.getString("student_id"),
                    rs.getString("gender"),
                    roleKorean,
                    rs.getString("birth_date")
                });
            }
        } catch (SQLException e) {
            System.err.println("회원 테이블 로드 중 오류 발생: " + e.getMessage());
            e.printStackTrace();
        }
    }

    // 성별 필터에 따라 회원 테이블 로드
    private void loadMemberTableByGender(String gender) {
        DefaultTableModel model = (DefaultTableModel) MemTable.getModel();
        model.setRowCount(0); // 초기화

        String sql;
        if ("전체".equals(gender)) {
            sql = "SELECT id, username, name, student_id, gender, role, birth_date FROM users";
        } else {
            sql = "SELECT id, username, name, student_id, gender, role, birth_date FROM users WHERE gender = ?";
        }

        try (Connection conn = new DBConnection().getConnection();
             PreparedStatement pstmt = conn.prepareStatement(sql)) {

            // 전체가 아닌 경우에만 파라미터 설정
            if (!"전체".equals(gender)) {
                pstmt.setString(1, gender);
            }

            try (ResultSet rs = pstmt.executeQuery()) {
                while (rs.next()) {
                    String role = rs.getString("role");
                    String roleKorean = convertRoleToKorean(role);

                    model.addRow(new Object[]{
                        rs.getInt("id"),
                        rs.getString("username"),
                        rs.getString("name"),
                        rs.getString("student_id"),
                        rs.getString("gender"),
                        roleKorean,
                        rs.getString("birth_date")
                    });
                }
            }
        } catch (SQLException e) {
            System.err.println("회원 테이블 로드 중 오류 발생: " + e.getMessage());
            e.printStackTrace();
        }
    }

