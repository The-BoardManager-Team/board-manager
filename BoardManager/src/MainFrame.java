    // role 영어를 한글로 변환
    private String convertRoleToKorean(String role) {
        switch (role) {
            case "admin":
                return "관리자";
            case "president":
                return "부장";
            case "member":
                return "회원";
            default:
                return role;
        }
    }

    // role 한글을 영어로 변환
    private String convertRoleToEnglish(String koreanRole) {
        switch (koreanRole) {
            case "관리자":
                return "admin";
            case "부장":
                return "president";
            case "평회원":
            case "회원":
                return "member";
            default:
                return koreanRole;
        }
    }

