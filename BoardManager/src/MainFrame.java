    private void loadDuesHistory(String sortOrder) {
        duesIds.clear();
        DefaultTableModel model = (DefaultTableModel) DuesTable.getModel();
        model.setRowCount(0);

        String sql = "SELECT id, usage_date, location, representative, description, amount " +
                     "FROM dues ORDER BY usage_date " + sortOrder;

        // 현재 총 회비와 사용 금액 계산
        int currentDues = getCurrentDues();
        int usedAmount = calculateUsedAmount();
        int currentBalance = currentDues - usedAmount;

        try (Connection conn = new DBConnection().getConnection();
             PreparedStatement pstmt = conn.prepareStatement(sql);
             ResultSet rs = pstmt.executeQuery()) {

            ArrayList<Object[]> rows = new ArrayList<>();
            ArrayList<Integer> ids = new ArrayList<>();

            while (rs.next()) {
                ids.add(rs.getInt("id"));
                rows.add(new Object[]{
                    rs.getString("usage_date"),
                    rs.getString("location"),
                    rs.getString("representative"),
                    rs.getString("description"),
                    rs.getInt("amount"),
                    null  // 잔액은 나중에 계산
                });
            }

            // 잔액 계산
            if ("DESC".equals(sortOrder)) {
                // 최신순: 현재 잔액부터 역으로 계산
                int balance = currentBalance;
                for (int i = 0; i < rows.size(); i++) {
                    duesIds.add(ids.get(i));
                    Object[] row = rows.get(i);
                    row[5] = balance;
                    balance += (int) row[4];
                    model.addRow(row);
                }
            } else {
                // 날짜순: 초기 잔액부터 순차적으로 계산
                int balance = currentDues;
                for (int i = 0; i < rows.size(); i++) {
                    duesIds.add(ids.get(i));
                    Object[] row = rows.get(i);
                    balance -= (int) row[4];
                    row[5] = balance;
                    model.addRow(row);
                }
            }

        } catch (SQLException e) {
            System.err.println("회비 내역 로드 중 오류 발생: " + e.getMessage());
            e.printStackTrace();
        }
    }

